"""
Video generation with Google Veo, through the Gemini API -- and the entry
point for every video model: Gemini Omni Flash requests are handed to
`omni.py`, which works differently (see there), but share the same job/poll
flow, gallery and sidecars.

Replaces Sora: OpenAI shut the Sora API down on 2026-09-24. Veo renders take
a minute or more, so this works like the old flow -- start a long-running
operation, return its name as the job id, and let the page poll until it is
done; the finished MP4 is downloaded into the same gallery as the images.

Plain REST over httpx rather than the google-genai SDK: it is three calls
(start, poll, download), and the SDK would be a large dependency for that.

A render can start from one of the generated images -- typically a finished
ULTEx ad -- so the clip opens on the real logo and layout instead of Veo
inventing a brand it cannot draw.

**Extension.** One Veo request is at most 8 seconds. Veo 3.1 can *extend* a
video it generated by 7 seconds at a time, up to 20 times (~148s), as one
continuous shot -- 720p only. Every finished Veo video gets a sidecar
`<file>.json` with what an extension needs (model, aspect, resolution,
length, Google's file uri), so any gallery video made here can be extended
later, and each extension is saved as a new file that can be extended again.
"""

